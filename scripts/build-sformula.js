#!/usr/bin/env node

/*
 * Builds the vendored sformula bundle used by the "Live Formula" feature on the
 * Show All Data page (addon/inspect.js -> addon/formula-eval.js).
 *
 * sformula (https://github.com/stomita/sformula) is an MIT-licensed Salesforce
 * formula parser/evaluator. It is published as an npm package with several
 * dependencies, so we bundle it (and its deps) into a single self-contained ESM
 * file that the extension can `import` directly - matching how the project
 * vendors other third-party libraries under addon/lib/ (e.g. flow-scanner-core).
 *
 * Usage:
 *   node scripts/build-sformula.js            # build pinned version
 *   node scripts/build-sformula.js 5.0.1      # build a specific version
 *
 * The custom entry re-exports the public API plus the lower-level helpers we
 * need for sub-expression evaluation (parseFormula gives the raw AST with `loc`
 * spans; createFieldTypeDictionary/extractFields support cross-object types).
 */

const {execSync} = require("child_process");
const fs = require("fs");
const path = require("path");
const os = require("os");

const SFORMULA_VERSION = process.argv[2] || "5.0.1";
const OUT_DIR = path.join(process.cwd(), "addon", "lib", "sformula");
const OUT_FILE = path.join(OUT_DIR, "sformula.js");

const colors = {green: "\x1b[32m", yellow: "\x1b[33m", red: "\x1b[31m", blue: "\x1b[34m", reset: "\x1b[0m"};
function log(message, color) {
  "use strict";
  console.log(`${colors[color || "reset"]}${message}${colors.reset}`);
}

function main() {
  "use strict";
  log("🚀 sformula vendoring build", "green");
  log(`Building sformula@${SFORMULA_VERSION} -> ${path.relative(process.cwd(), OUT_FILE)}`, "blue");

  const tempDir = path.join(os.tmpdir(), `sformula-build-${Date.now()}`);
  fs.mkdirSync(tempDir, {recursive: true});

  try {
    // Isolated install so we never touch the project's own dependencies.
    fs.writeFileSync(path.join(tempDir, "package.json"), JSON.stringify({name: "sformula-vendor", private: true, type: "module"}));

    log("\nInstalling sformula + esbuild in a temp dir…", "blue");
    execSync(`npm install sformula@${SFORMULA_VERSION} esbuild --no-audit --no-fund --loglevel=error`, {cwd: tempDir, stdio: "inherit"});

    const installedVersion = JSON.parse(fs.readFileSync(path.join(tempDir, "node_modules", "sformula", "package.json"), "utf8")).version;

    // Entry point: public API + helpers needed for per-node / cross-object eval.
    const entry = [
      'export * from "sformula";',
      'export { parseFormula } from "sformula/module/formula.js";',
      'export { extractFields } from "sformula/module/fieldExtraction.js";',
      'export { createFieldTypeDictionary } from "sformula/module/fieldType.js";',
      "",
    ].join("\n");
    fs.writeFileSync(path.join(tempDir, "entry.js"), entry);

    const banner = [
      "/*!",
      " * Vendored bundle of sformula (Salesforce formula parser/evaluator).",
      ` * sformula v${installedVersion} - MIT License - https://github.com/stomita/sformula`,
      " * Bundles: esformula, bignumber.js, dayjs, @babel/runtime (all MIT).",
      " * Generated by scripts/build-sformula.js - do not edit by hand.",
      " * See THIRD_PARTY_NOTICES.md for full attribution.",
      " */",
    ].join("\n");
    fs.writeFileSync(path.join(tempDir, "banner.txt"), banner);

    log("\nBundling to a single minified ESM file…", "blue");
    fs.mkdirSync(OUT_DIR, {recursive: true});
    const esbuildCmd = [
      "./node_modules/.bin/esbuild entry.js --bundle --format=esm --platform=browser",
      "--target=es2020 --minify --legal-comments=none --banner:js=\"$(cat banner.txt)\"",
      `--outfile="${OUT_FILE}"`,
    ].join(" ");
    execSync(esbuildCmd, {cwd: tempDir, stdio: "inherit", shell: "/bin/bash"});

    const sizeKb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1);
    log(`\n✓ Wrote ${path.relative(process.cwd(), OUT_FILE)} (${sizeKb} KB, sformula v${installedVersion})`, "green");
    log("Remember to update THIRD_PARTY_NOTICES.md if the version changed.", "yellow");
  } finally {
    fs.rmSync(tempDir, {recursive: true, force: true});
  }
}

if (require.main === module) {
  main();
}
module.exports = {main};
